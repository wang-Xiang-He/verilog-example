`timescale 1ns/1ps

// =====================================================================
// Decoder：3 對 8 解碼器，Out = 1'b1 << in
//   把數值 1 左移 in 次，所以第 in 個位元為 1、其餘為 0
// =====================================================================
module Decoder (in, Out);
    input  [2:0] in;
    output [7:0] Out;
    wire   [7:0] Out;

    assign Out = 1'b1 << in;
    // 1'b1 雖然只有 1 位元，但 Verilog 會依等號左邊 Out 的寬度（8 位元）來計算，所以左移不會被截掉
endmodule
