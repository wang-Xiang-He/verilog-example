`timescale 1ns/1ps

// =====================================================================
// DFF_pr：使用者自定的「邊緣觸發」D 型正反器（序向 UDP）（講義第 11~13 頁）
//   CLK 正緣（0 → 1）時 Q = D，其餘時間 Q 保持不變
//
// 序向 UDP 和組合 UDP 的差別（講義第 7 頁）：
//   1. 輸出要宣告成 reg（因為要記住狀態）
//   2. 真值表多一欄「目前狀態」：<輸入...> : <輸出現在狀態 Q(n)> : <輸出下一狀態 Q(n+1)> ;
//   3. 下一狀態寫 - 代表「不變」
//   4. (01) 這種括號表示「轉換」（邊緣）：(01) = 0 → 1 = 正緣；(?0) = 任何值 → 0
// =====================================================================
primitive DFF_pr (Q, D, CLK);
    output Q;
    reg    Q;
    input  D, CLK;

    table
    //  D   CLK  :  Q(n) :  Q(n+1)
        0  (01)  :   ?   :    0  ;   // 正緣 Q(n+1) = D (= 0)
        1  (01)  :   ?   :    1  ;   // 正緣 Q(n+1) = D (= 1)
        0  (0?)  :   0   :    0  ;   // 不確定的正緣（0 → x）：D 和 Q 一樣時，Q 不變
        1  (0?)  :   1   :    1  ;
        ?  (1?)  :   ?   :    -  ;   // CLK 由 1 變成其他值（負緣）：不變（講義第 12 頁的寫法）
        // ?  (??)  :   ?   :    -  ;   // 講義第 11 頁有這行，但它和上面的 (01) 列衝突 → 編譯錯誤，所以註解掉
        (??) ?   :   ?   :    -  ;   // D 改變但 CLK 沒有邊緣：不變（講義沒有，補上，否則 Q 會變成 x）
    endtable
endprimitive
