//   t=20  S1S0=01 D=1  ->  _1: Y3..Y0=0010   _2: Y3..Y0=0010
//   t=30  S1S0=01 D=0  ->  _1: Y3..Y0=0000   _2: Y3..Y0=0000
//   t=40  S1S0=10 D=1  ->  _1: Y3..Y0=0100   _2: Y3..Y0=0100
//   t=50  S1S0=10 D=0  ->  _1: Y3..Y0=0000   _2: Y3..Y0=0000
//   t=60  S1S0=11 D=1  ->  _1: Y3..Y0=1000   _2: Y3..Y0=1000
//   t=70  S1S0=11 D=0  ->  _1: Y3..Y0=0000   _2: Y3..Y0=0000
//   ** Note: $stop    : DeMux1X4_tb.v(21)          <- 執行到 $stop，模擬暫停，波形保留
