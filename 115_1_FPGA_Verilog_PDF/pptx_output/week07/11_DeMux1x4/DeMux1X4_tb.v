`timescale 1ns/1ps

// =====================================================================
// DeMux1X4_tb：兩種 1 對 4 解多工器一起測
//   S1 S0 跑 00~11，每一組 D 都給 1 再給 0
// =====================================================================
module DeMux1X4_tb;
    reg  D, S1, S0;
    wire [3:0] Y_1, Y_2;        // {Y3, Y2, Y1, Y0}
    integer k;

    DeMux1X4_1 u1 (.D(D), .S1(S1), .S0(S0), .Y0(Y_1[0]), .Y1(Y_1[1]), .Y2(Y_1[2]), .Y3(Y_1[3]));
    DeMux1X4_2 u2 (.D(D), .S1(S1), .S0(S0), .Y0(Y_2[0]), .Y1(Y_2[1]), .Y2(Y_2[2]), .Y3(Y_2[3]));

    initial begin
        $monitor("t=%0d  S1S0=%b%b D=%b  ->  _1: Y3..Y0=%b   _2: Y3..Y0=%b",
                 $time, S1, S0, D, Y_1, Y_2);
        for (k = 0; k < 8; k = k + 1) begin
            {S1, S0} = k / 2;  D = ~k[0]; #10;      // D 依序 1、0
        end
        $stop;
    end
endmodule


// =====================================================================
// 【預期輸出】ModelSim 的 Transcript 視窗（每行前面會多一個 # 號）
