`timescale 1ns/1ps

// =====================================================================
// fcpath_delay1：完全連接路徑（*>）時間延遲的設定（範例練習 7-006，講義第 36~38 頁）
//   電路：y = (a1 & a2) | (a3 & a4)
//     a1 ─┐
//         AND1 ── y1 ─┐
//     a2 ─┘           │
//                     OR1 ── y
//     a3 ─┐           │
//         AND2 ── y2 ─┘
//     a4 ─┘
// =====================================================================
module fcpath_delay1 (
    input  a1,
    input  a2,
    input  a3,
    input  a4,
    output y
);
    wire y1, y2;

    // (來源1, 來源2 *> 目的) = 延遲;   *> 是「完全連接路徑」：每一個來源到每一個目的都有路徑
    //   (a1, a2 *> y) = 10;  等於 11_PPath_Delay 的 (a1 => y) = 10; 加上 (a2 => y) = 10; 兩行
    specify
        (a1, a2 *> y) = 10;
        (a3, a4 *> y) = 12;
    endspecify

    and and1 (y1, a1, a2);
    and and2 (y2, a3, a4);
    or  or1  (y,  y1, y2);
endmodule
