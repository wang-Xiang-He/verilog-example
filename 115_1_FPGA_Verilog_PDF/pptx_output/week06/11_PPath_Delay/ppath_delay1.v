`timescale 1ns/1ps

// =====================================================================
// ppath_delay1：並列路徑（=>）時間延遲的設定（範例練習 7-005，講義第 32~35 頁）
//   電路：y = (a1 & a2) | (a3 & a4)
//     a1 ─┐
//         AND1 ── y1 ─┐
//     a2 ─┘           │
//                     OR1 ── y
//     a3 ─┐           │
//         AND2 ── y2 ─┘
//     a4 ─┘
// =====================================================================
module ppath_delay1 (
    input  a1,
    input  a2,
    input  a3,
    input  a4,
    output y
);
    wire y1, y2;

    // specify ... endspecify：模組路徑延遲（module path delay）
    //   (來源輸入埠 => 目的輸出埠) = 延遲時間;     => 是「並列路徑」：一個位元對一個位元
    //   延遲直接設在「輸入埠 → 輸出埠」這條路徑上，裡面的邏輯閘本身不設延遲
    specify
        (a1 => y) = 10;             // 路徑 a1 - y1 - y，延遲 10 單位時間
        (a2 => y) = 10;             // 路徑 a2 - y1 - y，延遲 10 單位時間
        (a3 => y) = 12;             // 路徑 a3 - y2 - y，延遲 12 單位時間
        (a4 => y) = 12;             // 路徑 a4 - y2 - y，延遲 12 單位時間
    endspecify

    and and1 (y1, a1, a2);
    and and2 (y2, a3, a4);
    or  or1  (y,  y1, y2);
endmodule
