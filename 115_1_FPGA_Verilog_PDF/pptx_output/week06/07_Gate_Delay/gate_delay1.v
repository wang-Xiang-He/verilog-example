`timescale 1ns/1ps

// =====================================================================
// gate_delay1：以邏輯閘層描述方式，設定個別邏輯閘的延遲（範例練習 7-001，講義第 20~22 頁）
//   電路：y = (a1 & a2) | (a3 & a4)
//     a1 ─┐
//         AND1 ── y1 ─┐
//     a2 ─┘           │
//                     OR1 ── y
//     a3 ─┐           │
//         AND2 ── y2 ─┘
//     a4 ─┘
// =====================================================================
module gate_delay1 (
    input  a1,
    input  a2,
    input  a3,
    input  a4,
    output y
);
    wire y1, y2;

    // 閘名 #延遲 實例名 (輸出, 輸入...);   延遲單位由 `timescale 決定（這裡 1ns）
    and #4  and1 (y1, a1, a2);      // y1 在輸入改變 4ns 後才變
    and #6  and2 (y2, a3, a4);      // y2 在輸入改變 6ns 後才變
    or  #10 or1  (y,  y1, y2);      // y  在 y1 / y2 改變 10ns 後才變
endmodule
