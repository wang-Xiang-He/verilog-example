`timescale 1ns/1ps

// =====================================================================
// wire_test：對照組（講義第 4 頁右上角「wire c;」的情況）
//   一般 wire 被兩個 assign 驅動，兩個值不同時會「打架」→ 結果是 x（未知）
//   實際電路這樣接會短路，所以一般設計中一條 wire 只能有一個驅動源
// =====================================================================
module wire_test (
    input  a,
    input  b,
    output c           // 預設就是 wire
);
    assign c = a;
    assign c = b;      // a != b 時 c = x
endmodule
