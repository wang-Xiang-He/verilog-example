// ============================================================
//  W12-2：三級管線乘法器
//  重點：★ 把一顆大乘法器【切成三段】，每段中間插一組正反器
//        每段都變短 → 時脈可以拉高 → 每秒算得更多
//
//  代價：延遲從 2 拍變成 4 拍。
//  ★★ 這就是管線的本質：用【延遲】換【吞吐量】。
//
//   單週期：  a,b ─[FF]─→【████整顆乘法器████】─[FF]─→ p
//                          一段很長，時脈只能慢
//
//   三級管線：a,b ─[FF]─→【██部分積██】─[FF]─→【██加█】─[FF]─→【█加█】─[FF]─→ p
//                          每段都短，時脈可以快
// ============================================================
`timescale 1ns / 1ps

module mult_pipe3 (
    input  wire        clk,
    input  wire        rst_n,
    input  wire        vld_in,
    input  wire [7:0]  a, b,

    output reg  [15:0] p,
    output reg         vld_out
);

    // ========================================================
    //  級 0：輸入暫存
    // ========================================================
    reg [7:0] a0, b0;
    reg       v0;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin a0 <= 0; b0 <= 0; v0 <= 0; end
        else        begin a0 <= a; b0 <= b; v0 <= vld_in; end
    end

    // ========================================================
    //  級 1：產生 8 個部分積，先兩兩相加成 4 個
    //
    //  部分積 = b 的第 i 位是 1 的話，就是 a<<i，否則是 0
    //  這就是直式乘法的每一列
    // ========================================================
    wire [15:0] pp0 = b0[0] ? {8'b0, a0}       : 16'd0;
    wire [15:0] pp1 = b0[1] ? {7'b0, a0, 1'b0} : 16'd0;
    wire [15:0] pp2 = b0[2] ? {6'b0, a0, 2'b0} : 16'd0;
    wire [15:0] pp3 = b0[3] ? {5'b0, a0, 3'b0} : 16'd0;
    wire [15:0] pp4 = b0[4] ? {4'b0, a0, 4'b0} : 16'd0;
    wire [15:0] pp5 = b0[5] ? {3'b0, a0, 5'b0} : 16'd0;
    wire [15:0] pp6 = b0[6] ? {2'b0, a0, 6'b0} : 16'd0;
    wire [15:0] pp7 = b0[7] ? {1'b0, a0, 7'b0} : 16'd0;

    reg [15:0] s1_0, s1_1, s1_2, s1_3;
    reg        v1;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            s1_0 <= 0; s1_1 <= 0; s1_2 <= 0; s1_3 <= 0; v1 <= 0;
        end else begin
            s1_0 <= pp0 + pp1;      // ★ 這一級只做「一次加法」
            s1_1 <= pp2 + pp3;
            s1_2 <= pp4 + pp5;
            s1_3 <= pp6 + pp7;
            v1   <= v0;
        end
    end

    // ========================================================
    //  級 2：4 個再兩兩相加成 2 個
    // ========================================================
    reg [15:0] s2_0, s2_1;
    reg        v2;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            s2_0 <= 0; s2_1 <= 0; v2 <= 0;
        end else begin
            s2_0 <= s1_0 + s1_1;
            s2_1 <= s1_2 + s1_3;
            v2   <= v1;
        end
    end

    // ========================================================
    //  級 3：最後兩個相加，得到答案
    // ========================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            p <= 0; vld_out <= 0;
        end else begin
            p       <= s2_0 + s2_1;
            vld_out <= v2;
        end
    end

    // ========================================================
    //  ★★ 注意 vld_in 這條線：v0 → v1 → v2 → vld_out
    //
    //  它跟著資料一起在管線裡走，每一級都要跟著推一格。
    //  這叫做【控制訊號要和資料對齊】，是管線設計最常出錯的地方 ——
    //  資料延遲了 4 拍，但你忘了把 valid 也延遲 4 拍，
    //  結果就是「答案是對的，但送出去的時間點錯了」。
    // ========================================================

endmodule

//  ---- 延遲 (latency)：4 拍
//  ---- 吞吐量 (throughput)：每拍 1 筆（和單週期版一樣！）
//  ---- 最高時脈：★ 比單週期版高，因為每一級的路徑都短了

