// ============================================================
//  W2-8：定點小數與「不用除法器的除法」   ← 課本 7.4.5 / 7.4.6 / 7.4.7 / 7.6 / 7.7
//  重點：★ 硬體裡沒有小數點，小數點是「你自己記住它在哪一位」
//        ★ 乘除法很貴，能用位移加法湊出來就別用 * 和 /
// ============================================================
`timescale 1ns / 1ps

module fixed_point (
    input  wire [7:0]  a,            // 一個普通的 8 位元無號整數

    // ---- 7.4.5 怎麼算 1.5 倍和 3 倍（不用乘法器）----
    output wire [8:0]  a_x1p5,       // 1.5*a = a + a/2
    output wire [9:0]  a_x3,         // 3*a   = 2a + a

    // ---- 7.4.6 怎麼算「除以 9」（不用除法器）----
    output wire [7:0]  a_div9_ref,   // 直接寫 a/9（會合成出一整顆除法器，很貴）
    output wire [7:0]  a_div9_fast,  // (a*57)>>9  ★ 對 8 位元完全精確

    // ---- 7.6 / 7.7 定點小數：Q4.4 格式 ----
    //  8 個位元，前 4 位是整數、後 4 位是小數
    //  例如 8'b0011_1000 = 3 + 8/16 = 3.5
    input  wire [7:0]  qa, qb,
    output wire [8:0]  q_add,        // Q4.4 + Q4.4 → Q5.4
    output wire [15:0] q_mul_full,   // Q4.4 * Q4.4 → Q8.8（完整結果）
    output wire [7:0]  q_mul_trunc,  // 直接截掉 → Q4.4（會一路少算）
    output wire [7:0]  q_mul_round   // ★ 7.4.7 四捨五入 → Q4.4
);

    // --------------------------------------------------------
    //  7.4.5  1.5 倍與 3 倍
    //  a>>1 就是 a/2、a<<1 就是 2a，位移在硬體上是「接線」，不用閘
    // --------------------------------------------------------
    assign a_x1p5 = a + (a >> 1);
    assign a_x3   = (a << 1) + a;

    // --------------------------------------------------------
    //  7.4.6  除以 9
    //  1/9 = 0.111111...，把它放大 2^9 倍 → 512/9 = 56.9 ≈ 57
    //  所以 a/9 ≈ (a*57)>>9。乘以常數 57 綜合工具會拆成幾次位移相加，
    //  比一顆真的除法器小非常多。
    //  ★ 對 0~255 的 a，這個近似式和 a/9 的結果「完全一樣」，一個都沒錯。
    // --------------------------------------------------------
    assign a_div9_ref  = a / 9;

    //  ★★ 這裡有個超級常見的坑：不能直接寫成
    //        assign a_div9_fast = (a * 8'd57) >> 9;      <-- 錯！
    //     因為 Verilog 會用「賦值左邊的寬度」去決定乘法要算幾位元。
    //     a_div9_fast 只有 8 位元 → a*57 先被砍成 8 位元 → 再右移 9 位 → 永遠是 0。
    //     解法：先用一條夠寬的 wire 把乘積接住，再移位。
    wire [15:0] a_times57 = a * 16'd57;      // 16 位元，接得住 255*57 = 14535
    assign a_div9_fast = a_times57 >> 9;

    // --------------------------------------------------------
    //  Q4.4 定點小數
    //  加法：小數點位置相同，直接加就好
    //  乘法：Q4.4 * Q4.4 = Q8.8，小數位數會「相加」變成 8 位
    //        要變回 Q4.4 就得把小數位砍掉 4 位
    // --------------------------------------------------------
    assign q_add      = qa + qb;
    assign q_mul_full = qa * qb;                    // Q8.8

    //  直接截斷：小數第 5 位以後全丟掉 → 永遠往下少算
    assign q_mul_trunc = q_mul_full[11:4];

    //  ★ 四捨五入：丟掉之前先加「半個 LSB」(1<<3 = 8)
    //    要丟 4 位 → 半個 LSB 就是 2^(4-1) = 8
    assign q_mul_round = (q_mul_full + 16'd8) >> 4;

endmodule

