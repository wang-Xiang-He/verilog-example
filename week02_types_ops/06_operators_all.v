// ============================================================
//  W2-6：運算子全集（每一個都在裡面）
//  重點：02_operators 只挑了代表，這份是「查得到就跑得到」的完整版
// ============================================================
`timescale 1ns / 1ps

module operators_all (
    input  wire [3:0] a,
    input  wire [3:0] b,

    // ---------- ① 算術 ----------
    output wire [4:0] o_add,      // +   多留一位裝進位
    output wire [4:0] o_sub,      // -
    output wire [7:0] o_mul,      // *   兩個 4 位元相乘要 8 位元
    output wire [3:0] o_div,      // /   整數除法，小數直接丟掉
    output wire [3:0] o_mod,      // %   餘數
    output wire [7:0] o_pow,      // **  次方（這裡固定算 a 的平方）
    output wire [3:0] o_neg,      // -a  單元負號（就是取二補數）

    // ---------- ② 位元（一位一位分別做，輸出跟輸入一樣寬）----------
    output wire [3:0] o_and,      // &
    output wire [3:0] o_or,       // |
    output wire [3:0] o_xor,      // ^
    output wire [3:0] o_xnor,     // ~^  (也可以寫 ^~)
    output wire [3:0] o_not,      // ~

    // ---------- ③ 邏輯（整條線當一個真假值，輸出永遠 1 位元）----------
    output wire       o_land,     // &&
    output wire       o_lor,      // ||
    output wire       o_lnot,     // !

    // ---------- ④ 關係（輸出永遠 1 位元）----------
    output wire       o_eq,       // ==
    output wire       o_ne,       // !=
    output wire       o_lt,       // <
    output wire       o_gt,       // >
    output wire       o_le,       // <=   ★ 這裡是「小於等於」，不是非阻塞賦值
    output wire       o_ge,       // >=
    output wire       o_ceq,      // ===  連 x/z 都要一模一樣才算相等
    output wire       o_cne,      // !==

    // ---------- ⑤ 縮減（一整條線縮成 1 位元）----------
    output wire       o_rand,     // &a
    output wire       o_ror,      // |a
    output wire       o_rxor,     // ^a   ← 奇偶檢查 parity
    output wire       o_rnand,    // ~&a
    output wire       o_rnor,     // ~|a
    output wire       o_rxnor,    // ~^a

    // ---------- ⑥ 位移 ----------
    output wire [3:0] o_shl,      // <<
    output wire [3:0] o_shr,      // >>   邏輯右移，左邊補 0
    output wire [3:0] o_ashl,     // <<<
    output wire [3:0] o_ashr      // >>>  算術右移，左邊補符號位（要 signed 才有差）
);

    // 同一條 a，換一個「有號」的身分來看。
    // >>> 和 >> 的差別只有在有號數上才看得出來。
    wire signed [3:0] sa = a;

    // ---------- ① 算術 ----------
    assign o_add  = a + b;
    assign o_sub  = a - b;
    assign o_mul  = a * b;
    assign o_div  = a / b;        // ★ b=0 時整條變 x（硬體上除法器本來就沒定義）
    assign o_mod  = a % b;        // ★ 同上
    assign o_pow  = a ** 2;
    assign o_neg  = -a;           // 4 位元裡的 -a = 16-a

    // ---------- ② 位元 ----------
    assign o_and  = a & b;
    assign o_or   = a | b;
    assign o_xor  = a ^ b;
    assign o_xnor = a ~^ b;
    assign o_not  = ~a;

    // ---------- ③ 邏輯 ----------
    assign o_land = a && b;       // a 非零 而且 b 非零
    assign o_lor  = a || b;       // a 非零 或者 b 非零
    assign o_lnot = !a;           // a 是 0 → 1

    // ---------- ④ 關係 ----------
    assign o_eq   = (a == b);
    assign o_ne   = (a != b);
    assign o_lt   = (a <  b);
    assign o_gt   = (a >  b);
    assign o_le   = (a <= b);
    assign o_ge   = (a >= b);
    assign o_ceq  = (a === b);    // ★ 只能模擬，不能合成
    assign o_cne  = (a !== b);

    // ---------- ⑤ 縮減 ----------
    assign o_rand  =  &a;         // a[3]&a[2]&a[1]&a[0]
    assign o_ror   =  |a;
    assign o_rxor  =  ^a;         // 1 的個數是奇數 → 1
    assign o_rnand = ~&a;
    assign o_rnor  = ~|a;
    assign o_rxnor = ~^a;

    // ---------- ⑥ 位移 ----------
    assign o_shl  = a  << 1;
    assign o_shr  = a  >> 1;
    assign o_ashl = sa <<< 1;     // <<< 跟 << 其實一樣，左移沒有符號問題
    assign o_ashr = sa >>> 1;     // ★ 右移時補的是符號位，不是 0

endmodule




