// ============================================================
//  W2-4：多工器（用三元運算子 ? : ）
//  重點：多工器 = 電子式的切換開關，是數位電路最常用的零件之一
// ============================================================
`timescale 1ns / 1ps

module mux (
    input  wire [3:0] d0, d1, d2, d3,   // 四路輸入
    input  wire [1:0] sel,              // 選哪一路
    output wire [3:0] y2,               // 2 選 1（只用 sel[0]）
    output wire [3:0] y4                // 4 選 1
);

    //  三元運算子：條件 ? 真的時候 : 假的時候
    //
    //         d0 ──┐
    //              ├──○\
    //         d1 ──┘   │ ├── y2
    //              sel[0]/
    //
    assign y2 = sel[0] ? d1 : d0;

    //  4 選 1 = 三個 2 選 1 疊起來，可以寫成巢狀三元
    assign y4 = (sel == 2'd0) ? d0 :
                (sel == 2'd1) ? d1 :
                (sel == 2'd2) ? d2 :
                                d3;

endmodule
