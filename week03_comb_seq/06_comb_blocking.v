// ============================================================
//  W3-6：組合邏輯裡用錯 <= 會怎樣
//
//  第 4 個範例示範的是「時脈區塊用錯 = 」→ 3 顆正反器塌成 1 顆
//  這個範例示範另一半：「組合區塊用錯 <=」→ 產生毛刺
//
//  兩邊用錯的後果剛好相反，但都是錯的。
// ============================================================
`timescale 1ns / 1ps

module comb_blocking (
    input  wire a, b, c,
    output reg  y_ok,        // always @(*) 裡用 =   ← 正確
    output reg  y_bad        // always @(*) 裡用 <=  ← 錯誤
);

    reg tmp1, tmp2;

    //  電路：y = (a & b) | c
    //  中間值 tmp = a & b

    // ---------- ✅ 正確：用 = （阻塞）----------
    //  「這句做完才做下一句」→ 第二句看得到剛算好的 tmp1
    always @(*) begin
        tmp1 = a & b;
        y_ok = tmp1 | c;
    end

    // ---------- ❌ 錯誤：用 <= （非阻塞）----------
    //  「先把右邊全部讀好，再一起寫左邊」
    //  → 第二句讀 tmp2 的時候，第一句的結果還沒寫進去
    //  → 讀到的是「上一次」的 tmp2 → 輸出先錯一下才追上
    always @(*) begin
        tmp2  <= a & b;
        y_bad <= tmp2 | c;
    end

endmodule
