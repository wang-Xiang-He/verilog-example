// ============================================================
//  W3-8：解多工器 (DeMultiplexer)     ← 課本 8.1.5
//  重點：多工器是「多選一」，解多工器是「一送多」—— 剛好相反
// ============================================================
`timescale 1ns / 1ps

module demux (
    input  wire       din,        // 一條進來
    input  wire [2:0] sel,        // 要送到哪一條
    input  wire       en,

    output reg  [7:0] dout,       // 八條出去，只有被選中那條有值
    output reg  [7:0] dout_bus    // 沒被選中的送 z（高阻抗）而不是 0
);

    // --------------------------------------------------------
    //  一般版：沒選到的送 0
    //  ★ 先給預設值 8'b0 是關鍵，否則 sel 沒涵蓋到的情況會生 latch
    // --------------------------------------------------------
    always @(*) begin
        dout = 8'b0;              // 預設全 0（第 3 週的 latch 防呆）
        if (en) dout[sel] = din;  // 只點亮一條
    end

    // --------------------------------------------------------
    //  匯流排版：沒選到的送 z
    //  用在「很多個裝置共用一條線」的場合（下一個範例 11 會詳細講）
    // --------------------------------------------------------
    always @(*) begin
        dout_bus = 8'bzzzz_zzzz;
        if (en) dout_bus[sel] = din;
    end

endmodule

