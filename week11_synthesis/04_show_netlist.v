`timescale 1ns / 1ps

// ------------------------------------------------------------
//  一、小到看得懂的東西：全加器
//  ★ 從這個開始畫，因為只有幾顆閘，圖看得清楚
// ------------------------------------------------------------
module fa (
    input  wire a, b, cin,
    output wire sum, cout
);
    assign sum  = a ^ b ^ cin;
    assign cout = (a & b) | (b & cin) | (a & cin);
endmodule


// ------------------------------------------------------------
//  二、有階層的東西：2 位元加法器
//  ★ 畫出來會看到兩顆 fa 方塊，以及它們之間的進位線
//    這就是第 10 週階層式設計在綜合工具眼中的樣子
// ------------------------------------------------------------
module adder2 (
    input  wire [1:0] a, b,
    input  wire       cin,
    output wire [1:0] sum,
    output wire       cout
);
    wire c1;
    fa u0 (.a(a[0]), .b(b[0]), .cin(cin), .sum(sum[0]), .cout(c1));
    fa u1 (.a(a[1]), .b(b[1]), .cin(c1),  .sum(sum[1]), .cout(cout));
endmodule


// ------------------------------------------------------------
//  三、有正反器的東西：2 位元計數器
//  ★ 畫出來會看到 DFF 方塊，還有從輸出繞回輸入的那條【回授線】
//    那條線就是「記憶」的來源
// ------------------------------------------------------------
module counter2 (
    input  wire       clk,
    input  wire       rst_n,
    output reg  [1:0] q
);
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) q <= 2'd0;
        else        q <= q + 2'd1;
    end
endmodule


// ------------------------------------------------------------
//  四、多工器：看它變成什麼
//  ★ 一個 2 選 1 多工器在 iCE40 上會變成【一顆 LUT】——
//    因為 4 輸入查表本來就能表示任何 4 變數的布林函數
// ------------------------------------------------------------
module mux2 (
    input  wire [1:0] a, b,
    input  wire       sel,
    output wire [1:0] y
);
    assign y = sel ? a : b;
endmodule

