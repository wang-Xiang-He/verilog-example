`timescale 1ns / 1ps

// ------------------------------------------------------------
//  一、純組合邏輯：4 位元加法器
//  預期綜合結果：只有 LUT，一顆正反器都沒有
// ------------------------------------------------------------
module adder4 (
    input  wire [3:0] a, b,
    input  wire       cin,
    output wire [3:0] sum,
    output wire       cout
);
    assign {cout, sum} = a + b + cin;
endmodule


// ------------------------------------------------------------
//  二、有記憶的電路：4 位元計數器
//  預期綜合結果：4 顆正反器 + 一些 LUT
// ------------------------------------------------------------
module counter4 (
    input  wire       clk,
    input  wire       rst_n,
    input  wire       en,
    output reg  [3:0] count
);
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)  count <= 4'd0;
        else if (en) count <= count + 4'd1;
    end
endmodule


// ------------------------------------------------------------
//  三、比較大的東西：8 位元乘法器
//  ★ 看看一顆乘法器到底有多貴
// ------------------------------------------------------------
module mult8 (
    input  wire [7:0]  a, b,
    output wire [15:0] p
);
    assign p = a * b;
endmodule


// ------------------------------------------------------------
//  四、對照組：8 位元加法器
//  和上面的乘法器比，就知道「乘法很貴」到底貴到什麼程度
// ------------------------------------------------------------
module add8 (
    input  wire [7:0] a, b,
    output wire [8:0] s
);
    assign s = a + b;
endmodule

