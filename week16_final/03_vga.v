// ============================================================
//  期末專題 第 3 題：VGA 訊號產生器
//  難度：★★☆   考的是：第 3、4、10 週（計數器 + 參數化 + 階層式）
//  配分：100 分
// ============================================================
`timescale 1ns / 1ps

//  ============================================================
//  規格：640x480 @ 60Hz，像素時脈 25.175 MHz
//  ============================================================
//
//  VGA 是類比訊號，但【時序】完全是數位的：
//  一個畫面就是一台巨大的雙層迴圈計數器。
//
//  ------------------------------------------------------------
//  水平方向（單位：像素）
//
//     |<---- 640 可見 ---->|<-16->|<--96-->|<-48->|
//     ┌────────────────────┐      ┌────────┐
//     │      畫面內容       │      │        │
//     └────────────────────┘──────┘        └──────
//                            前緣   同步脈衝  後緣
//     總共 800 個像素時間
//
//  ------------------------------------------------------------
//  垂直方向（單位：掃描線）
//
//     480 可見 + 10 前緣 + 2 同步 + 33 後緣 = 525 條
//
//  ------------------------------------------------------------
//  ★ 為什麼有「前緣、同步、後緣」這些看不到的區域？
//     因為 VGA 是為映像管螢幕設計的 ——
//     電子槍掃完一行要花時間【飛回】左邊，那段時間不能有畫面。
//     液晶螢幕早就不需要了，但規格沿用至今。
//
//  ------------------------------------------------------------
//  ⚠️ hsync 和 vsync 在 640x480@60Hz 是【低準位有效】
//     （同步期間輸出 0，其他時間輸出 1）
//
//  ------------------------------------------------------------
//  ⚠️ 像素時脈：標準是 25.175 MHz。
//     12MHz 的板子做不出來，實務上會用 PLL 倍頻到 25.175MHz，
//     或直接用 25MHz（誤差 0.7%，多數螢幕吃得下）。
//     本題只做時序產生器，不管時脈怎麼來。
//  ============================================================

module vga_sync #(
    //  ---- 水平參數 ----
    parameter H_VISIBLE = 640,
    parameter H_FRONT   = 16,
    parameter H_SYNC    = 96,
    parameter H_BACK    = 48,
    //  ---- 垂直參數 ----
    parameter V_VISIBLE = 480,
    parameter V_FRONT   = 10,
    parameter V_SYNC    = 2,
    parameter V_BACK    = 33
) (
    input  wire       clk,          // 像素時脈
    input  wire       rst_n,

    output wire       hsync,        // ★ 低準位有效
    output wire       vsync,        // ★ 低準位有效
    output wire       video_on,     // 1 = 現在在可見區
    output wire [9:0] pixel_x,      // 0 ~ H_VISIBLE-1（可見區外的值不管）
    output wire [9:0] pixel_y,
    output wire       frame_start   // 每張畫面開始時高一拍
);

    localparam H_TOTAL = H_VISIBLE + H_FRONT + H_SYNC + H_BACK;   // 800
    localparam V_TOTAL = V_VISIBLE + V_FRONT + V_SYNC + V_BACK;   // 525

    // ========================================================
    //  ★★★ 在這裡寫你的答案 ★★★
    // ========================================================
    //
    //  ---- 提示：兩個巢狀的計數器 ----
    //
    //    reg [9:0] h_cnt, v_cnt;
    //
    //    h_cnt 每個時脈 +1，數到 H_TOTAL-1 歸零
    //    v_cnt 只在 h_cnt 歸零的那一拍 +1，數到 V_TOTAL-1 歸零
    //
    //    ★ 這就是「行掃完換下一行，掃完整張畫面回到第一行」
    //
    //  ---- 各訊號怎麼算 ----
    //
    //    hsync：h_cnt 落在 [H_VISIBLE+H_FRONT, H_VISIBLE+H_FRONT+H_SYNC-1]
    //           這個區間時輸出 0，其他時候 1
    //           → 640+16=656 到 656+96-1=751 之間是 0
    //
    //    vsync：同理，v_cnt 在 [490, 491] 之間是 0
    //
    //    video_on：h_cnt < H_VISIBLE 而且 v_cnt < V_VISIBLE
    //
    //    pixel_x / pixel_y：直接就是 h_cnt / v_cnt
    //
    //    frame_start：h_cnt==0 而且 v_cnt==0 的那一拍
    //
    //  ---- ⚠️ 三個容易錯的地方 ----
    //    1. hsync/vsync 是【低】準位有效，不要寫反
    //    2. v_cnt 只能在 h_cnt 歸零時才動，不是每拍都動
    //    3. 邊界用 < 還是 <=，差一格就會整個畫面歪掉

    assign hsync       = 1'b1;      // ← 補完後刪掉這些預設值
    assign vsync       = 1'b1;
    assign video_on    = 1'b0;
    assign pixel_x     = 10'd0;
    assign pixel_y     = 10'd0;
    assign frame_start = 1'b0;

endmodule


// ============================================================
//  第 2 部分：畫個東西上去（用上面的時序產生器）
//  ------------------------------------------------------------
//  要求：畫一個 8x6 的棋盤格
//        每格 80x80 像素，(x/80 + y/80) 是偶數就白色，奇數就黑色
//
//  ⚠️ 除法很貴（第 11 週）。80 不是 2 的次方，
//     但你可以用別的方法 —— 想想看每格 80 像素要怎麼不用除法算出來。
//     （提示：本題允許直接用 /，但想拿滿分的話試試看別的做法）
// ============================================================
module vga_pattern (
    input  wire       clk,
    input  wire       rst_n,
    output wire       hsync,
    output wire       vsync,
    output wire [2:0] rgb          // {r,g,b}，各 1 位元
);

    wire       video_on;
    wire [9:0] px, py;

    vga_sync u_sync (
        .clk(clk), .rst_n(rst_n),
        .hsync(hsync), .vsync(vsync),
        .video_on(video_on), .pixel_x(px), .pixel_y(py),
        .frame_start()
    );

    // ★★★ 在這裡寫你的答案 ★★★
    //
    //  提示：
    //    1. video_on=0 的時候 rgb 一定要是 000
    //       （消隱期間送顏色會讓螢幕認不出訊號）
    //    2. 棋盤格：wire cell = (px/80) + (py/80); rgb = cell[0] ? 000 : 111;

    assign rgb = 3'b000;      // ← 補完後刪掉

endmodule

