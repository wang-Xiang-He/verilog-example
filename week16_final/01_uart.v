    // ⚠️ tick 只能高【一拍】，高兩拍會讓 UART 快一倍。

    assign tick = 1'b0;      // ← 先給預設值，把上面補完後刪掉這行

endmodule


// ============================================================
//  第 2 部分：發送器（40 分）
// ============================================================
module uart_tx #(
    parameter TICKS = 104
) (
    input  wire       clk,
    input  wire       rst_n,
    input  wire       send,
    input  wire [7:0] data,
    output reg        tx,
    output wire       busy
);

    // ★★★ 在這裡寫你的答案 ★★★
    //
    // 提示：用第 6 週的三段式狀態機，四個狀態：
    //   IDLE  → 等 send。tx=1
    //   START → 送起始位元。tx=0，持續 1 個位元時間
    //   DATA  → 送 8 個資料位元，每個位元時間推一位（PISO，第 3 週）
    //   STOP  → 送停止位元。tx=1，持續 1 個位元時間
    //
    // ⚠️ 三個很容易錯的地方：
    //   1. tx 一定要【上正反器】，用 assign 會有毛刺
    //   2. LSB first —— 先送 data[0]，不是 data[7]
    //   3. busy 要在 IDLE 以外都是 1

    assign busy = 1'b0;      // ← 補完後刪掉

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) tx <= 1'b1;
        else        tx <= 1'b1;     // ← 補完後改掉
    end

endmodule


// ============================================================
//  第 3 部分：接收器（40 分）★ 這題最難
// ============================================================
module uart_rx #(
    parameter TICKS = 104
) (
    input  wire       clk,
    input  wire       rst_n,
    input  wire       rx,
    output reg  [7:0] data_out,
    output reg        valid,
    output reg        frame_err
);

    // ★★★ 在這裡寫你的答案 ★★★
    //
    // 提示：
    //   1. rx 是外部訊號 → ★ 先做兩級同步器（第 15 週的第一個坑）
    //   2. 等 rx 從 1 掉到 0（起始位元）
    //   3. ★★ 等 TICKS/2 拍，對齊到【起始位元的中央】
    //      然後每隔 TICKS 拍取樣一次，就會剛好都在每個位元的中央
    //   4. 收 8 位元進移位暫存器（LSB first → 從右邊推進、往右移）
    //   5. 再等一個位元時間看停止位元：
    //        是 1 → 正常，valid 拉高一拍
    //        是 0 → frame_err 也拉高一拍
    //
    // ⚠️ 為什麼要對齊中央？
    //    因為發送端和接收端的時脈【不完全一樣】（鮑率誤差）。
    //    在位元邊緣附近取樣，誤差一累積就會取到隔壁位元。
    //    取中央的話，左右各有半個位元時間的容錯。

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            data_out  <= 8'd0;
            valid     <= 1'b0;
            frame_err <= 1'b0;
        end else begin
            valid     <= 1'b0;      // ← 補完後改掉
            frame_err <= 1'b0;
        end
    end

endmodule

