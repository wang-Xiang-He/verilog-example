// ============================================================
//  期末專題 第 1 題：UART 收發器（含鮑率產生器）
//  難度：★★☆   考的是：第 3、6、15 週
//  配分：100 分（測試平台會自動判分）
// ============================================================
`timescale 1ns / 1ps

//  ============================================================
//  規格
//  ============================================================
//
//  格式：8N1（8 個資料位元、無同位、1 個停止位元）
//  順序：LSB first（先送最低位）
//
//     閒置  起始   d0  d1 ... d7   停止  閒置
//     ▔▔▔▔╲___╱▔╲__╱▔ ... ▔╲___╱▔▔▔▔▔
//
//  鮑率：每一位持續 BAUD_TICKS = CLK_HZ / BAUD 個時脈
//
//  ------------------------------------------------------------
//  發送器 uart_tx
//    send=1 一拍  → 把 data 送出去
//    傳送期間 busy=1，結束後回到 0
//    busy=1 時再給 send 要【忽略】
//
//  接收器 uart_rx
//    偵測到起始位元（tx 線從 1 掉到 0）就開始收
//    ★ 要對齊到【位元中央】取樣
//    收滿 8 位元後，data_out 給值、valid 拉高【一拍】
//    停止位元不對的話 frame_err 拉高一拍（data_out 還是要給）
//  ============================================================


// ============================================================
//  第 1 部分：鮑率產生器（20 分）
//  ------------------------------------------------------------
//  要求：
//    en=1 時開始數，每數到 TICKS-1 就把 tick 拉高【一拍】
//    en=0 時計數器歸零、tick 保持 0
// ============================================================
module baud_gen #(
    parameter TICKS = 104
) (
    input  wire clk,
    input  wire rst_n,
    input  wire en,
    output wire tick
);

    // ★★★ 在這裡寫你的答案 ★★★
    //
    // 提示：
    //   1. 宣告一個夠寬的計數器（TICKS 可能很大，寬度要用 clog2 算）
    //   2. en=0 → 歸零
    //   3. 數到 TICKS-1 → tick=1 而且下一拍歸零
