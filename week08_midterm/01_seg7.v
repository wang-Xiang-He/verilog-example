`timescale 1ns / 1ps

//  七段顯示器的段位命名（共陽極/共陰極先不管，這裡用「1 = 亮」）
//
//        aaa
//       f   b
//       f   b
//        ggg
//       e   c
//       e   c
//        ddd
//
//  seg 的位元順序是 {g, f, e, d, c, b, a}  → seg[0]=a, seg[6]=g
//
//  要求：
//    bcd 是 0~9 時，seg 輸出對應的字型
//    bcd 是 10~15 時，seg 全滅（7'b0000000）

module seg7 (
    input  wire [3:0] bcd,
    output reg  [6:0] seg
);

    always @(*) begin
        // ★★★ 在這裡寫你的答案 ★★★
        //
        // 提示：用 case (bcd)，每個數字對應一組 7 位元的值。
        //       例如數字 0 要亮 a,b,c,d,e,f 不亮 g → 7'b0111111
        //       數字 1 只亮 b,c                    → 7'b0000110
        //
        // 記得寫 default！

        seg = 7'b0000000;   // ← 先給預設值（避免 latch），然後把下面的 case 補完

    end

endmodule
